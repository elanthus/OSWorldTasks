#!/usr/bin/env python3
"""Generate the BC v2 diagnosis report from stored structured evidence only.

Reads ``artifacts/bc-diagnosis-v1/diagnosis.json`` and ``artifacts/bc-diagnosis-v1/probes/*.json``
and writes ``artifacts/bc-diagnosis-v1/REPORT.md``. It reruns nothing. Overall tables list every
run; per-field, per-position and per-widget detail tables show the two runs with the largest
demonstration count in each split (a fixed rule in this file, not chosen by result). All values
for every run are in the JSON.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
FOLDER = Path("artifacts/bc-diagnosis-v1")
PROBES = ("legibility", "convergence", "copy")


def pct(num: int, den: int) -> str:
    return "—" if den == 0 else f"{100 * num / den:.1f}%"


def detail_runs(diagnosis: dict[str, Any], split: str) -> list[str]:
    runs = {n: r for n, r in diagnosis["runs"].items() if r["split"] == split}
    top = max(r["demo_episodes"] for r in runs.values())
    return sorted(n for n, r in runs.items() if r["demo_episodes"] == top)


def agreement_row(label: str, a: dict[str, int]) -> str:
    n = a["frames"]
    return (
        f"| {label} | {n} | {pct(a['policy_correct'], n)} | {pct(a['baseline_correct'], n)} | "
        f"{a['policy_only']} | {a['baseline_only']} | {a['both_correct']} | {a['neither']} |"
    )


AGREEMENT_HEADER = (
    "| {first} | Key frames | Policy | Card-blind | Only policy right | Only card-blind right | "
    "Both right | Neither |\n|---|---:|---:|---:|---:|---:|---:|---:|"
)


def render(diagnosis: dict[str, Any], probes: dict[str, dict[str, Any]]) -> str:
    lines = [
        "# Behaviour cloning v2: diagnosis",
        "",
        (
            "Generated by `scripts/generate_bc_diagnosis_report.py` from `diagnosis.json` and "
            f"`probes/*.json` in this folder. The diagnosis was recorded at revision "
            f"`{diagnosis['git_revision']}` (worktree clean: "
            f"{'yes' if diagnosis['worktree_clean'] else 'no'}) from the BC v2 results recorded at "
            f"`{diagnosis['source_results_revision']}`, on {diagnosis['host']['platform']}, torch "
            f"{diagnosis['host']['torch']}, device `{diagnosis['host']['device']}`, in "
            f"{diagnosis['seconds']} s. No model was trained for the diagnosis."
        ),
        "",
        (
            "Before any closed-loop replay, each run's stored weights matched the SHA-256 in "
            "`results.json` and reproduced its stored teacher-forced predictions with the "
            "mismatch counts below. Regenerated test demonstrations equalled "
            "`test-frames-<split>.json`."
        ),
        "",
        "## Keys",
        "",
        (
            "The card-blind baseline is the v2 definition: the most frequent training "
            "continuation of the keys already typed into the clicked control. It never sees the "
            "request card. Position is the number of keys typed into the field before this one."
        ),
        "",
        AGREEMENT_HEADER.format(first="Run"),
    ]
    for name, run in diagnosis["runs"].items():
        lines.append(agreement_row(f"`{name}`", run["keys"]["overall"]))
    lines.append("")
    for split, info in diagnosis["splits"].items():
        for name in detail_runs(diagnosis, split):
            keys = diagnosis["runs"][name]["keys"]
            lines += [f"### `{name}`: keys by field", "", AGREEMENT_HEADER.format(first="Field")]
            lines += [agreement_row(f, a) for f, a in keys["by_field"].items()]
            lines += [
                "",
                f"### `{name}`: keys by position",
                "",
                AGREEMENT_HEADER.format(first="Position"),
            ]
            lines += [agreement_row(p, a) for p, a in keys["by_position"].items()]
            guess = keys["by_baseline_guess"]
            lines += [
                "",
                f"### `{name}`: keys by whether the correct key is the card-blind guess",
                "",
                AGREEMENT_HEADER.format(first="Correct key"),
                agreement_row("is the card-blind guess", guess["correct_key_is_baseline_guess"]),
                agreement_row("is not", guess["correct_key_is_not_baseline_guess"]),
                "",
            ]
        lines.append(
            f"Split `{split}`: {info['key_frames']} key frames; card-blind key accuracy "
            f"{100 * info['baseline_key_accuracy']:.1f}%."
        )
        lines.append("")
    lines += ["## Clicks", ""]
    for split in diagnosis["splits"]:
        for name in detail_runs(diagnosis, split):
            clicks = diagnosis["runs"][name]["clicks"]
            lines += [
                f"### `{name}`: click target by oracle widget",
                "",
                "| Oracle target | Clicks | Correct | Wrong choices (count) |",
                "|---|---:|---:|---|",
            ]
            for widget, c in clicks["by_target_widget"].items():
                wrong = ", ".join(f"{k} ({v})" for k, v in c["wrong_choices"].items()) or "—"
                lines.append(
                    f"| {widget} | {c['clicks']} | {pct(c['correct'], c['clicks'])} | {wrong} |"
                )
            lines += [
                "",
                f"### `{name}`: click target by click number in the episode",
                "",
                "| Click number | Clicks | Correct |",
                "|---:|---:|---:|",
            ]
            for number, c in clicks["by_click_number"].items():
                lines.append(f"| {number} | {c['clicks']} | {pct(c['correct'], c['clicks'])} |")
            lines.append("")
    lines += [
        "## First wrong action in each closed-loop episode",
        "",
        (
            "Each test episode is replayed with the run's stored weights and compared step by "
            "step with the oracle's plan, using the v2 step rule (action type; for a click, the "
            "control and option hit; for a key, the key). Frame drift counts episodes whose "
            "closed-loop frame already differed from the oracle's before the first wrong action."
        ),
        "",
        (
            "| Run | Prediction mismatches on reload | Episodes | With a wrong action | "
            "Action type | Click target | Key | First wrong step min / median / max | "
            "Frame drift |"
        ),
        "|---|---:|---:|---:|---:|---:|---:|---|---:|",
    ]
    for name, run in diagnosis["runs"].items():
        f = run["first_wrong_action"]
        mismatch = sum(run["predictions_reproduced_mismatches"].values())
        kinds = f["by_kind"]
        lines.append(
            f"| `{name}` | {mismatch} | {f['episodes']} | {f['with_wrong_action']} | "
            f"{kinds.get('action_type', 0)} | {kinds.get('click_target', 0)} | "
            f"{kinds.get('key', 0)} | "
            f"{f['step_min']} / {f['step_median']} / {f['step_max']} | "
            f"{f['episodes_with_frame_drift_before_first_wrong']} |"
        )
    lines.append("")
    for split in diagnosis["splits"]:
        for name in detail_runs(diagnosis, split):
            f = diagnosis["runs"][name]["first_wrong_action"]
            by_field = ", ".join(f"{k} {v}" for k, v in sorted(f["by_field_for_keys"].items()))
            by_pos = ", ".join(f"{k}: {v}" for k, v in f["by_position_for_keys"].items())
            by_widget = ", ".join(
                f"{k} {v}" for k, v in sorted(f["by_oracle_click_widget"].items())
            )
            lines.append(
                f"- `{name}`: first wrong keys by field: {by_field or '—'}; by position: "
                f"{by_pos or '—'}; first wrong clicks by oracle target: {by_widget or '—'}."
            )
    lines += ["", "## Probes", ""]
    leg = probes.get("legibility")
    if leg:
        c = leg["config"]
        lines += [
            "### Legibility of one request-card character",
            "",
            (
                f"A small classifier ({c['classifier']}, {c['steps']} steps) names the centre "
                f"character of a crop around each card character. Trained on {leg['train_crops']} "
                f"crops from {c['train_seeds']}; scored on {leg['held_out_crops']} crops from "
                f"{c['held_out_seeds']}. Majority-class accuracy on the held-out crops: "
                f"{100 * leg['held_out_majority_class_accuracy']:.1f}%."
            ),
            "",
            "| Input | Crop (h×w) | Held-out accuracy |",
            "|---|---|---:|",
            (
                f"| policy resolution (384x512 grayscale) | {c['crop_policy_resolution'][0]}×"
                f"{c['crop_policy_resolution'][1]} | "
                f"{100 * leg['resolutions']['low']['held_out_accuracy']:.1f}% |"
            ),
            (
                f"| full resolution (768x1024 grayscale) | {c['crop_full_resolution'][0]}×"
                f"{c['crop_full_resolution'][1]} | "
                f"{100 * leg['resolutions']['full']['held_out_accuracy']:.1f}% |"
            ),
            "",
            "| Field | Crops | Policy resolution | Full resolution |",
            "|---|---:|---:|---:|",
        ]
        for field, low in leg["resolutions"]["low"]["by_field"].items():
            full = leg["resolutions"]["full"]["by_field"][field]
            lines.append(
                f"| {field} | {low['crops']} | {100 * low['accuracy']:.1f}% | "
                f"{100 * full['accuracy']:.1f}% |"
            )
        lines.append("")
    conv = probes.get("convergence")
    if conv:
        c = conv["config"]
        start, tf = conv["validation_at_start"], conv["test_teacher_forced_at_best"]
        cl = conv["test_closed_loop_at_best"]
        lines += [
            "### Convergence",
            "",
            (
                f"`{c['run']}` continued from step {c['start_step']} ({c['optimizer_state']}). "
                f"Stopped: {conv['stop_reason']}, after {conv['train_seconds']} s. Best validation "
                f"step accuracy {100 * conv['best_validation_step_accuracy']:.1f}% at step "
                f"{conv['best_validation_step']}, from {100 * start['step_accuracy']:.1f}% at "
                f"step {c['start_step']}."
            ),
            "",
            "| Step | Validation step | Click target | Key |",
            "|---:|---:|---:|---:|",
        ]
        for point in conv["validation_curve"]:
            lines.append(
                f"| {point['step']} | {100 * point['step_accuracy']:.1f}% | "
                f"{100 * point['click_target_accuracy']:.1f}% | "
                f"{100 * point['key_accuracy']:.1f}% |"
            )
        lines += [
            "",
            (
                f"Selected checkpoint on the test frames (scored once, after selection): step "
                f"{100 * tf['step_accuracy']:.1f}%, click target "
                f"{100 * tf['click_target_accuracy']:.1f}%, key {100 * tf['key_accuracy']:.1f}%; "
                f"closed loop {cl['successes']}/{cl['episodes']} successes, "
                f"{cl['mean_fields_correct']:.2f}/{cl['fields_total']} fields."
            ),
            "",
        ]
    cp = probes.get("copy")
    if cp:
        c = cp["config"]
        lines += [
            "### Capacity to copy one episode's keys",
            "",
            (
                f"{c['key_frames']} key frames ({c['distinct_keys']} distinct keys) from "
                f"{c['episode']}; {c['steps']} full-batch steps, {c['optimizer']}."
            ),
            "",
            "| Variant | Step | Training key accuracy |",
            "|---|---:|---:|",
        ]
        for variant in ("scratch_full_network", "stored_weights_key_branch_only"):
            curve = cp[variant]["curve"]
            for point in (curve[0], curve[len(curve) // 2], curve[-1]):
                lines.append(
                    f"| {c['variants'][variant]} | {point['step']} | "
                    f"{100 * point['train_key_accuracy']:.1f}% |"
                )
        lines.append("")
    lines += [
        "## Probe provenance",
        "",
        "| Probe | Revision | Worktree clean | Device | Seconds | Command |",
        "|---|---|---|---|---:|---|",
    ]
    for name in PROBES:
        if name in probes:
            p = probes[name]["provenance"]
            lines.append(
                f"| {name} | `{p['git_revision'][:12]}` | "
                f"{'yes' if p['worktree_clean'] else 'no'} | "
                f"`{p['device']}` | {probes[name]['total_seconds']} | `{probes[name]['command']}` |"
            )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repository-root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(argv)
    folder = args.repository_root / FOLDER
    diagnosis = json.loads((folder / "diagnosis.json").read_text(encoding="utf-8"))
    probes = {
        name: json.loads((folder / "probes" / f"{name}.json").read_text(encoding="utf-8"))
        for name in PROBES
        if (folder / "probes" / f"{name}.json").is_file()
    }
    (folder / "REPORT.md").write_text(render(diagnosis, probes), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
