#!/usr/bin/env python3
"""Generate the Chromium reset-determinism report from stored evidence files only.

Reads one or more JSON files written by ``scripts/run_chromium_reset_determinism.py`` (one per
host) and writes a Markdown report. It reruns nothing and applies no tolerance. Where two hosts
both stored the first frame of a seed as a PNG, it adds the raw pixel difference between them.

    .venv/bin/python scripts/generate_chromium_reset_determinism_report.py \\
        artifacts/chromium-reset-determinism-v1/macos-arm64.json \\
        artifacts/chromium-reset-determinism-v1/linux-ci.json \\
        --output artifacts/chromium-reset-determinism-v1/REPORT.md
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from scripts.run_chromium_reset_determinism import SCHEMA_VERSION, raw_difference

DEFINITIONS = (
    "- **Semantic determinism**: the reset task record and the privileged DOM form state have the "
    "same SHA-256 on every reset. Measured.\n"
    "- **Bitwise visual determinism**: the RGB frame bytes have the same SHA-256. Measured, within "
    "each host and across hosts.\n"
    "- **Perceptual visual stability**: a tolerance-based similarity. Not computed here; no "
    "tolerance is applied to any number below."
)


def host_label(evidence: dict[str, Any]) -> str:
    p = evidence["provenance"]["platform"]
    return f"{p['system']} {p['machine']}"


def load(path: Path) -> dict[str, Any]:
    evidence = json.loads(path.read_text(encoding="utf-8"))
    if evidence.get("schema_version") != SCHEMA_VERSION:
        raise ValueError(f"{path}: unexpected schema {evidence.get('schema_version')!r}")
    return evidence


def _frame(root: Path, evidence: dict[str, Any], seed: int) -> np.ndarray | None:
    """Reset-0 PNG of ``seed``, from the frames directory beside the evidence file.

    The directory is found by its recorded name next to the evidence file, so a file recorded
    elsewhere (for example a CI workspace) still resolves after it is checked in unchanged.
    """
    from PIL import Image

    if not evidence.get("frames_dir"):
        return None
    folder = (root / evidence["_path"]).parent / Path(evidence["frames_dir"]).name
    path = folder / f"seed-{seed}-reset-0.png"
    if not path.is_file():
        return None
    with Image.open(path) as image:
        return np.asarray(image.convert("RGB"), dtype=np.uint8)


def cross_host(root: Path, a: dict[str, Any], b: dict[str, Any]) -> list[dict[str, Any]]:
    seeds_a = {s["seed"]: s for s in a["per_seed"]}
    seeds_b = {s["seed"]: s for s in b["per_seed"]}
    rows = []
    for seed in sorted(set(seeds_a) & set(seeds_b)):
        ha, hb = seeds_a[seed]["distinct_frame_sha256"], seeds_b[seed]["distinct_frame_sha256"]
        row: dict[str, Any] = {
            "seed": seed,
            "frame_hashes_equal": ha == hb,
            "task_equal": seeds_a[seed]["distinct_task_sha256"]
            == seeds_b[seed]["distinct_task_sha256"],
            "form_state_equal": seeds_a[seed]["distinct_form_state_sha256"]
            == seeds_b[seed]["distinct_form_state_sha256"],
            "raw": None,
        }
        fa, fb = _frame(root, a, seed), _frame(root, b, seed)
        if fa is not None and fb is not None:
            row["raw"] = raw_difference(fa, fb)
            # The PNG must decode to the frame the evidence hashed, or the raw numbers are moot.
            from scripts.run_chromium_reset_determinism import frame_sha256

            row["png_matches_reset_0"] = [
                frame_sha256(fa) == seeds_a[seed]["resets"][0]["frame_sha256"],
                frame_sha256(fb) == seeds_b[seed]["resets"][0]["frame_sha256"],
            ]
        rows.append(row)
    return rows


def _yn(value: bool) -> str:
    return "yes" if value else "no"


def render(root: Path, paths: list[Path], evidences: list[dict[str, Any]]) -> str:
    lines = [
        "# Chromium reset determinism",
        "",
        "Generated by `scripts/generate_chromium_reset_determinism_report.py` from "
        + ", ".join(f"`{p.as_posix()}`" for p in paths)
        + ". Each file was recorded by `scripts/run_chromium_reset_determinism.py` on the host "
        "named below, in local Playwright Chromium, without the OSWorld guest.",
        "",
        "## Terms",
        "",
        DEFINITIONS,
        "",
    ]
    for path, ev in zip(paths, evidences, strict=True):
        p = ev["provenance"]
        lines += [
            f"## {host_label(ev)} (`{path.name}`)",
            "",
            (
                f"- Revision `{p['git_revision']}`, worktree clean: {_yn(p['worktree_clean'])}; "
                f"recorded {p['recorded_at_utc']}."
            ),
            (
                f"- {p['platform']['system']} {p['platform']['release']} "
                f"({p['platform']['machine']}), Python {p['platform']['python']}, "
                f"Playwright {p['playwright']}, Chromium {p['chromium_version']}."
            ),
            (
                f"- Renderer contract `{p['renderer_contract']['identity']}`; viewport "
                f"{p['viewport'][0]}x{p['viewport'][1]}; {p['isolation']}."
            ),
            (
                f"- {len(ev['seeds'])} seeds × {ev['resets_per_seed']} resets; "
                f"{ev['total_seconds']} s in total."
            ),
            "",
            (
                "| Seed | Resets | Distinct frame hashes | Distinct task hashes | "
                "Distinct form-state hashes | Differing frame pairs | Max differing pixels | "
                "Max per-channel delta |"
            ),
            "|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for s in ev["per_seed"]:
            pairs = [d for d in s["differing_frame_pairs"] if d.get("comparable")]
            max_px = max((d["differing_pixel_count"] for d in pairs), default=0)
            max_delta = max((d["max_per_channel_delta"] for d in pairs), default=0)
            lines.append(
                f"| {s['seed']} | {len(s['resets'])} | {len(s['distinct_frame_sha256'])} | "
                f"{len(s['distinct_task_sha256'])} | {len(s['distinct_form_state_sha256'])} | "
                f"{len(s['differing_frame_pairs'])}/{s['pair_count']} | {max_px} | {max_delta} |"
            )
        lines.append("")
    for (pa, a), (pb, b) in itertools.combinations(zip(paths, evidences, strict=True), 2):
        rows = cross_host(root, a, b)
        equal = sum(1 for r in rows if r["frame_hashes_equal"])
        same_contract = a["provenance"]["renderer_contract"] == b["provenance"]["renderer_contract"]
        lines += [
            f"## Across hosts: {host_label(a)} vs {host_label(b)}",
            "",
            (
                f"Frame hash sets equal on {equal} of {len(rows)} common seeds. Chromium "
                f"{a['provenance']['chromium_version']} vs {b['provenance']['chromium_version']}; "
                f"renderer contract identical: {_yn(same_contract)}."
            ),
            "",
            (
                "| Seed | Frame hashes equal | Task equal | Form state equal | "
                "Differing pixels (reset 0) | Max per-channel delta | Differing bbox |"
            ),
            "|---:|---|---|---|---:|---:|---|",
        ]
        for r in rows:
            raw = r["raw"]
            if raw is None:
                px = delta = bbox = "no PNG"
            elif not raw["comparable"]:
                px = delta = bbox = "shapes differ"
            elif not all(r["png_matches_reset_0"]):
                px = delta = bbox = "PNG does not match recorded hash"
            else:
                px, delta = raw["differing_pixel_count"], raw["max_per_channel_delta"]
                bbox = raw["differing_pixel_bbox_xyxy"]
            lines.append(
                f"| {r['seed']} | {_yn(r['frame_hashes_equal'])} | {_yn(r['task_equal'])} | "
                f"{_yn(r['form_state_equal'])} | {px} | {delta} | {bbox} |"
            )
        lines.append("")
    lines += [
        "## Scope",
        "",
        (
            "Local Playwright Chromium, not the OSWorld guest's Chrome, not the guest bundle and "
            "not the guest's display stack. Cross-host bitwise identity is reported as measured "
            "above and is claimed only for seeds whose hash sets are equal."
        ),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("evidence", type=Path, nargs="+")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--repository-root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(argv)
    root = args.repository_root
    paths = [p if not p.is_absolute() else p.relative_to(root) for p in args.evidence]
    evidences = [{**load(root / p), "_path": p} for p in paths]
    args.output.write_text(render(root, paths, evidences), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
